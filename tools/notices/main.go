// Command notices writes THIRD_PARTY_NOTICES.txt: the license and notice
// files of all third-party code compiled into the rodin3d-mcp binary, for
// every release target. That is the Go standard library and runtime, each
// Go module the build links (with the license files of vendored code inside
// them), and the code of the embedded Draco decoder module (Draco, wasi-libc
// and the LLVM runtimes, from internal/draco).
//
// Run from the repository root:
//
//	go run ./tools/notices          # write the file
//	go run ./tools/notices -check   # exit 1 when the file is out of date
//
// The module files are read from the module cache (go mod download fills
// it), so the output depends only on go.sum and the Go version.
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

const output = "THIRD_PARTY_NOTICES.txt"

// targets are the release targets of .goreleaser.yml.
var targets = [][2]string{
	{"darwin", "amd64"}, {"darwin", "arm64"},
	{"linux", "amd64"}, {"linux", "arm64"},
	{"windows", "amd64"}, {"windows", "arm64"},
}

// licenseFile matches the names of license and notice files.
var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents|unlicense)([-._].*)?$`)

// wasmFiles are the notice and license files of the Draco decoder module,
// in the order they are printed.
var wasmFiles = []string{
	"internal/draco/NOTICE",
	"internal/draco/LICENSE-draco",
	"internal/draco/licenses/wasi-libc/LICENSE",
	"internal/draco/licenses/wasi-libc/LICENSE-APACHE-LLVM",
	"internal/draco/licenses/wasi-libc/LICENSE-APACHE",
	"internal/draco/licenses/wasi-libc/LICENSE-MIT",
	"internal/draco/licenses/wasi-libc/musl-COPYRIGHT",
	"internal/draco/licenses/wasi-libc/cloudlibc-LICENSE",
	"internal/draco/licenses/wasi-libc/dlmalloc-NOTICE",
	"internal/draco/licenses/llvm/libcxx-LICENSE.TXT",
	"internal/draco/licenses/llvm/libcxxabi-LICENSE.TXT",
	"internal/draco/licenses/llvm/compiler-rt-LICENSE.TXT",
}

type module struct {
	path, version, dir string
	dirs               map[string]bool // package directories inside dir
}

func main() {
	check := flag.Bool("check", false, "exit 1 when "+output+" is out of date instead of writing it")
	flag.Parse()
	text, err := build()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	if *check {
		old, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(normalize(old), []byte(text)) {
			fmt.Fprintln(os.Stderr, "notices: "+output+" is out of date; run go run ./tools/notices")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(output, []byte(text), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func build() (string, error) {
	modules := map[string]*module{}
	usesStd := false
	for _, t := range targets {
		if err := list(t[0], t[1], modules, &usesStd); err != nil {
			return "", err
		}
	}
	var b strings.Builder
	b.WriteString("Third-party notices for rodin3d-mcp\n\n")
	b.WriteString("The rodin3d-mcp binary contains the third-party code listed below. Each\n")
	b.WriteString("section names the code and reproduces its license and notice files.\n")
	b.WriteString("This file is generated by tools/notices; `rodin3d-mcp licenses` prints it.\n")

	if usesStd {
		goroot, err := goEnv("GOROOT")
		if err != nil {
			return "", err
		}
		ver, err := goEnv("GOVERSION")
		if err != nil {
			return "", err
		}
		section(&b, "The Go standard library and runtime ("+ver+")")
		for _, name := range []string{"LICENSE", "PATENTS"} {
			if err := file(&b, filepath.Join(goroot, name), name); err != nil {
				return "", err
			}
		}
	}

	paths := make([]string, 0, len(modules))
	for p := range modules {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		m := modules[p]
		files, err := licenseFiles(m)
		if err != nil {
			return "", err
		}
		section(&b, "Go module "+m.path+" "+m.version)
		if len(files) == 0 {
			// A module without a license file states its license in its
			// README; that statement is reproduced.
			text, name, err := readmeLicense(m.dir)
			if err != nil {
				return "", fmt.Errorf("module %s@%s: %v", m.path, m.version, err)
			}
			b.WriteString("\nThe module ships no license file. The License section of its " + name + " reads:\n\n")
			b.WriteString(text + "\n")
			continue
		}
		for _, f := range files {
			rel, _ := filepath.Rel(m.dir, f)
			if err := file(&b, f, filepath.ToSlash(rel)); err != nil {
				return "", err
			}
		}
	}

	section(&b, "The Draco decoder module internal/draco/draco_decoder.wasm")
	for _, f := range wasmFiles {
		if err := file(&b, filepath.FromSlash(f), f); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

// list adds the modules the main package links for goos/goarch.
func list(goos, goarch string, modules map[string]*module, usesStd *bool) error {
	cmd := exec.Command("go", "list", "-deps", "-f",
		`{{if .Module}}{{if not .Module.Main}}M|{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}|{{.Dir}}|{{with .Module.Replace}}R{{.Version}}{{end}}{{end}}{{else}}{{if .Standard}}S{{end}}{{end}}`, ".")
	cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0", "GOFLAGS=-mod=readonly")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("go list for %s/%s: %v: %s", goos, goarch, err, stderr.String())
	}
	sc := bufio.NewScanner(bytes.NewReader(out))
	for sc.Scan() {
		line := sc.Text()
		if line == "S" {
			*usesStd = true
			continue
		}
		f := strings.Split(line, "|")
		if len(f) != 6 || f[0] != "M" {
			continue
		}
		path, version, dir, pkgDir, repl := f[1], f[2], f[3], f[4], f[5]
		switch {
		case repl == "R":
			// A module replaced by a directory of this repository
			// (third_party/hideconsole) is this project's own code.
			continue
		case repl != "":
			version = strings.TrimPrefix(repl, "R")
		}
		m := modules[path]
		if m == nil {
			m = &module{path: path, version: version, dir: dir, dirs: map[string]bool{}}
			modules[path] = m
		}
		m.dirs[pkgDir] = true
	}
	return sc.Err()
}

// licenseFiles are the license files of the module root and of every
// directory between the root and a linked package (vendored code keeps its
// own license next to it).
func licenseFiles(m *module) ([]string, error) {
	seen := map[string]bool{}
	var out []string
	add := func(dir string) error {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		for _, e := range entries {
			if e.IsDir() || !licenseFile.MatchString(e.Name()) {
				continue
			}
			p := filepath.Join(dir, e.Name())
			if !seen[p] {
				seen[p] = true
				out = append(out, p)
			}
		}
		return nil
	}
	if err := add(m.dir); err != nil {
		return nil, err
	}
	dirs := make([]string, 0, len(m.dirs))
	for d := range m.dirs {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	for _, d := range dirs {
		rel, err := filepath.Rel(m.dir, d)
		if err != nil || rel == "." || strings.HasPrefix(rel, "..") {
			continue
		}
		cur := m.dir
		for _, part := range strings.Split(rel, string(filepath.Separator)) {
			cur = filepath.Join(cur, part)
			if err := add(cur); err != nil {
				return nil, err
			}
		}
	}
	// Root files first, then the vendored ones by path.
	slices.SortStableFunc(out, func(a, b string) int {
		da, db := filepath.Dir(a) == m.dir, filepath.Dir(b) == m.dir
		switch {
		case da && !db:
			return -1
		case db && !da:
			return 1
		}
		return strings.Compare(a, b)
	})
	return out, nil
}

// readmeLicense returns the License section of the module's README (from its
// heading to the next heading of the same or a higher level).
func readmeLicense(dir string) (text, name string, err error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", "", err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasPrefix(strings.ToLower(e.Name()), "readme") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return "", "", err
		}
		lines := strings.Split(string(normalize(data)), "\n")
		for i, l := range lines {
			level := len(l) - len(strings.TrimLeft(l, "#"))
			if level == 0 || !strings.EqualFold(strings.TrimSpace(l[level:]), "license") {
				continue
			}
			end := len(lines)
			for j := i + 1; j < len(lines); j++ {
				if n := len(lines[j]) - len(strings.TrimLeft(lines[j], "#")); n > 0 && n <= level {
					end = j
					break
				}
			}
			body := strings.TrimSpace(strings.Join(lines[i:end], "\n"))
			return body, e.Name(), nil
		}
	}
	return "", "", errors.New("no license file and no License section in a README")
}

func section(b *strings.Builder, title string) {
	b.WriteString("\n\n")
	b.WriteString(strings.Repeat("=", 78) + "\n")
	b.WriteString(title + "\n")
	b.WriteString(strings.Repeat("=", 78) + "\n")
}

func file(b *strings.Builder, path, name string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	data = normalize(data)
	if len(bytes.TrimSpace(data)) == 0 {
		return errors.New(path + " is empty")
	}
	b.WriteString("\n--- " + name + " ---\n\n")
	b.Write(bytes.TrimRight(data, "\n"))
	b.WriteString("\n")
	return nil
}

// normalize makes line ends LF (the repository's .gitattributes stores text
// with LF, and a Windows checkout of the module cache may hold CRLF).
func normalize(data []byte) []byte {
	return bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
}

func goEnv(name string) (string, error) {
	out, err := exec.Command("go", "env", name).Output()
	if err != nil {
		return "", fmt.Errorf("go env %s: %v", name, err)
	}
	return strings.TrimSpace(string(out)), nil
}
